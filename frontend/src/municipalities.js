// Specific municipalities (excluding 'ALL') for Admin Jurisdiction assignment
export const SPECIFIC_MUNICIPALITIES = LANAO_DEL_NORTE_MUNICIPALITIES.filter(m => m.id !== 'ALL');

export function getMunicipalityById(muniId) {
  if (!muniId) return LANAO_DEL_NORTE_MUNICIPALITIES[0];
  const upper = String(muniId).trim().toUpperCase();
  const exact = LANAO_DEL_NORTE_MUNICIPALITIES.find(
    m =>
      m.id === upper ||
      m.shortName.toUpperCase() === upper ||
      m.name.toUpperCase() === upper
  );
  if (exact) return exact;

  const partial = SPECIFIC_MUNICIPALITIES.find(m =>
    m.keywords.some(k => upper.includes(k.toUpperCase()) || k.toUpperCase().includes(upper))
  );
  return partial || LANAO_DEL_NORTE_MUNICIPALITIES[0];
}

/**
 * Returns all registered places (barangays & landmarks) for a given municipality ID (or all municipalities if 'ALL').
 */
export function getRegisteredPlacesForMunicipality(muniId = 'ALL') {
  if (!muniId || muniId === 'ALL') {
    const allPlaces = [];
    for (const m of SPECIFIC_MUNICIPALITIES) {
      for (const p of m.places || []) {
        allPlaces.push({
          ...p,
          municipalityId: m.id,
          municipalityName: m.shortName
        });
      }
    }
    return allPlaces;
  }

  const muniObj = getMunicipalityById(muniId);
  if (!muniObj || muniObj.id === 'ALL') return [];
  return (muniObj.places || []).map(p => ({
    ...p,
    municipalityId: muniObj.id,
    municipalityName: muniObj.shortName
  }));
}

/**
 * Searches registered barangays & landmarks strictly within the active municipality (or province if 'ALL').
 */
export function searchMunicipalityPlaces(query, muniId = 'ALL') {
  const registered = getRegisteredPlacesForMunicipality(muniId);
  const clean = (query || '').trim().toLowerCase();
  if (!clean) {
    return registered.slice(0, 12);
  }

  // Score matches: exact match > startsWith > includes
  const scored = [];
  for (const place of registered) {
    const pName = place.name.toLowerCase();
    const fullLabel = `${place.name} ${place.municipalityName}`.toLowerCase();
    if (pName === clean || fullLabel === clean) {
      scored.push({ place, score: 100 });
    } else if (pName.startsWith(clean)) {
      scored.push({ place, score: 80 });
    } else if (pName.includes(clean) || fullLabel.includes(clean)) {
      scored.push({ place, score: 50 });
    }
  }

  scored.sort((a, b) => b.score - a.score || a.place.name.localeCompare(b.place.name));
  return scored.map(s => s.place);
}

function haversineKm(lat1, lon1, lat2, lon2) {
  const R = 6371;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

/**
 * Checks whether an incident belongs to a specific municipality jurisdiction
 * via explicit municipality field, location/title/description keywords, or geographic coordinates.
 */
export function doesIncidentBelongToMunicipality(inc, muniId) {
  if (!muniId || muniId === 'ALL') return true;
  const targetMuni = getMunicipalityById(muniId);
  if (!targetMuni || targetMuni.id === 'ALL') return true;

  if (inc.municipality && String(inc.municipality).toUpperCase() === targetMuni.id) {
    return true;
  }

  const combinedText = `${inc.location_name || ''} ${inc.title || ''} ${inc.description || ''}`.toLowerCase();

  // Check if text explicitly matches target municipality keywords or registered barangays
  if (
    targetMuni.keywords.some(kw => combinedText.includes(kw.toLowerCase())) ||
    (targetMuni.places || []).some(p => combinedText.includes(p.name.toLowerCase()) && p.name.toLowerCase() !== 'poblacion')
  ) {
    return true;
  }

  // Check if text explicitly mentions a different municipality
  const mentionsOtherMuni = SPECIFIC_MUNICIPALITIES.some(
    other =>
      other.id !== targetMuni.id &&
      other.keywords.some(kw => combinedText.includes(kw.toLowerCase()))
  );
  if (mentionsOtherMuni) {
    return false;
  }

  // Fall back to coordinate proximity (inside the wide municipal bounds or nearest municipality)
  const lat = parseFloat(inc.latitude);
  const lng = parseFloat(inc.longitude);
  if (!isNaN(lat) && !isNaN(lng)) {
    const padLat = targetMuni.boundsPadLat || targetMuni.boundsPad || 0.13;
    const padLng = targetMuni.boundsPadLng || targetMuni.boundsPad || 0.16;
    const withinWideBox =
      Math.abs(lat - targetMuni.lat) <= padLat &&
      Math.abs(lng - targetMuni.lng) <= padLng;

    let closestMuni = SPECIFIC_MUNICIPALITIES[0];
    let minDist = haversineKm(lat, lng, closestMuni.lat, closestMuni.lng);
    for (let i = 1; i < SPECIFIC_MUNICIPALITIES.length; i++) {
      const m = SPECIFIC_MUNICIPALITIES[i];
      const d = haversineKm(lat, lng, m.lat, m.lng);
      if (d < minDist) {
        minDist = d;
        closestMuni = m;
      }
    }
    return (closestMuni.id === targetMuni.id && minDist <= 28) || (withinWideBox && minDist <= 18);
  }

  return false;
}

/**
 * Checks whether an evacuation shelter belongs to a specific municipality jurisdiction.
 */
export function doesShelterBelongToMunicipality(shelter, muniId) {
  if (!muniId || muniId === 'ALL') return true;
  const targetMuni = getMunicipalityById(muniId);
  if (!targetMuni || targetMuni.id === 'ALL') return true;

  const sMuni = (shelter.municipality || '').toLowerCase();
  return (
    sMuni === targetMuni.id.toLowerCase() ||
    sMuni.includes(targetMuni.shortName.toLowerCase()) ||
    targetMuni.keywords.some(kw => sMuni.includes(kw.toLowerCase()))
  );
}
